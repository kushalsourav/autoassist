"""Offline tests for one-backend REST adapter and source-level migration.

Full LangChain/AG-UI integration still requires dependencies and model credentials.
"""
from __future__ import annotations

import asyncio
from pathlib import Path
from types import SimpleNamespace
import sys
import types
from uuid import uuid4

import pytest

from backend.app.agent_analysis import run_analysis, _answer_text


class HumanMessage:
    def __init__(self, content):
        self.content = content


class AIMessage:
    def __init__(self, content, tool_calls=None):
        self.content = content
        self.tool_calls = tool_calls or []


class FakeSnapshot:
    def __init__(self, messages=()):
        self.values = {'messages': list(messages)}


class FakeAgent:
    def __init__(self, warm=False):
        self.warm = warm
        self.calls = []

    async def aget_state(self, config):
        return FakeSnapshot([HumanMessage('earlier')] if self.warm else [])

    async def ainvoke(self, state, config):
        self.calls.append((state, config))
        return {'messages': [AIMessage('Answer generated by the real shared agent')],
                'classification': {}, 'documents': [], 'recall_status': 'not_queried'}


@pytest.fixture
def fake_langchain(monkeypatch):
    core = types.ModuleType('langchain_core')
    msgs = types.ModuleType('langchain_core.messages')
    msgs.HumanMessage = HumanMessage
    msgs.AIMessage = AIMessage
    core.messages = msgs
    agent = types.ModuleType('agent.story_agent')
    fake = FakeAgent()
    agent.story_graph = fake
    monkeypatch.setitem(sys.modules, 'langchain_core', core)
    monkeypatch.setitem(sys.modules, 'langchain_core.messages', msgs)
    monkeypatch.setitem(sys.modules, 'agent.story_agent', agent)
    return fake


def request():
    return SimpleNamespace(message='My brakes vibrate', make='Honda', model='Accord', year=2018)


def test_adapter_reads_histories_only_on_cold_checkpoint(fake_langchain):
    history = [{'role': 'user', 'content': 'Earlier question'},
               {'role': 'assistant', 'content': 'Earlier response'}]
    result = asyncio.run(run_analysis(request(), history, owner_id='alice', conversation_id='chat-one'))
    assert result['answer'] == 'Answer generated by the real shared agent'
    assert result['classification']['method'] == 'not_requested_by_agent'
    assert result['generation_mode'] == 'langchain_agent'
    sent, config = fake_langchain.calls[-1]
    assert len(sent['messages']) == 3
    assert isinstance(sent['messages'][-1], HumanMessage)
    assert '2018 Honda Accord' in sent['messages'][-1].content
    assert config['configurable']['thread_id'] == 'rest:alice:chat-one'

    fake_langchain.warm = True
    asyncio.run(run_analysis(request(), history, owner_id='alice', conversation_id='chat-one'))
    sent, _ = fake_langchain.calls[-1]
    assert len(sent['messages']) == 1  # prevents duplicated history


def test_ephemeral_threads_use_unique_ids(fake_langchain):
    asyncio.run(run_analysis(request(), []))
    asyncio.run(run_analysis(request(), []))
    a = fake_langchain.calls[-2][1]['configurable']['thread_id']
    b = fake_langchain.calls[-1][1]['configurable']['thread_id']
    assert a != b
    assert a.startswith('rest-ephemeral:')


def test_final_answer_filters_tool_calls_and_reasoning_blocks(fake_langchain):
    state = {'messages': [AIMessage('tool pending', tool_calls=[{'name': 'test'}]),
                          AIMessage([{'type': 'reasoning', 'text': 'DO NOT SHOW'},
                                     {'type': 'text', 'text': 'Public final answer'}])]}
    assert _answer_text(state) == 'Public final answer'


def test_unified_import_paths_and_no_old_graph():
    root = Path(__file__).resolve().parents[2]
    main = (root / 'backend/app/main.py').read_text()
    compat = (root / 'backend/app/copilot_server.py').read_text()
    factory = (root / 'agent/runtime/factory.py').read_text()
    assert 'from agent.workflow import analysis_graph' not in main
    assert 'analysis_graph.ainvoke' not in main
    assert 'from backend.app.agent_analysis import run_analysis' in main
    assert 'mount_agent(app)' in main
    assert 'from backend.app.main import app' in compat
    assert factory.count('return create_agent(') == 1
